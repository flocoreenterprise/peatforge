import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./fireEvents.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const { fireHeadline, eventForDetection, classLabel } = context.exports;
assert.equal(fireHeadline(null), null);
assert.equal(fireHeadline({ available: false, headline: { land_event_count: 0 } }), null);
assert.equal(fireHeadline({ headline: { land_event_count: null } }), null);
assert.match(fireHeadline({ headline: { land_event_count: 3, peat_event_count: 1, excluded_detection_count: 2 } }), /3 kejadian kebakaran lahan terklasifikasi \(1 di atas gambut\) · 2 deteksi dikecualikan/);
assert.match(fireHeadline({ headline: { land_event_count: 0 } }), /belum tersedia di atas gambut/);
assert.match(fireHeadline({ headline: { land_event_count: 0, peat_event_count: 0, excluded_detection_count: 0 } }), /0 kejadian/);
const item = { id: 'event', classification: 'industri', detection_ids: ['detection-a'], confirmed: false };
assert.equal(eventForDetection({ items: [item] }, 'detection-a'), item);
assert.equal(eventForDetection({ items: [item] }, 'other'), undefined);
assert.equal(eventForDetection({ available: false, items: [item] }, 'detection-a'), undefined);
assert.equal(classLabel('lahan_vegetasi'), 'Kandidat kebakaran vegetasi');
assert.equal(classLabel(undefined), 'Klasifikasi belum pasti');
console.log('PASS: candidate headline availability and explicit zero; exact detection membership; uncertain fallback');
