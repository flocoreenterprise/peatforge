// Offline HTTP fakes only; no server, provider, microphone or demo-state writes.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const requests = [];
const context = { exports: {}, AbortSignal, fetch: async (url, options) => { requests.push({ url, options }); return { ok: true, json: async () => ({ items: [] }) }; } };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./client.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const { publicRequest, parseStoredSession, publicSessionDenied, PublicError, publicActionLabel } = context.exports;
const token = 'synthetic_public_token_abcdefghijk';
const session = { token, village_id: 'v1', village_name: 'Desa contoh' };
assert.equal(parseStoredSession(JSON.stringify(session)).village_id, 'v1');
for (const invalid of [null, 'invalid', '{}', JSON.stringify({ ...session, token: 'bad' }), JSON.stringify({ token })]) assert.equal(parseStoredSession(invalid), null);
const controller = new AbortController();
await publicRequest('messages', token, controller.signal, { text: 'asap tipis', event_id: 'offline-event' });
assert.equal(requests[0].url, '/api/public/messages');
assert.equal(requests[0].options.credentials, 'omit', 'public identity never uses operator cookies');
assert.equal(requests[0].options.headers.Authorization, `Bearer ${token}`);
assert.ok(!requests[0].url.includes(token), 'session token never enters the URL');
assert.deepEqual(JSON.parse(requests[0].options.body), { text: 'asap tipis', event_id: 'offline-event' });
for (const status of [401, 403, 404]) assert.equal(publicSessionDenied(new PublicError(status)), true);
assert.equal(publicSessionDenied(new PublicError(503)), false);
context.fetch = async (url, options) => { requests.push({ url, options }); return { ok: false, status: 503 }; };
await assert.rejects(publicRequest('voice/session', token, controller.signal, {}), error => error instanceof PublicError && error.status === 503);
assert.equal(requests[1].url, '/api/public/voice/session', 'unavailable voice uses only the public boundary, never operator or provider sessions');
assert.equal(requests.length, 2, 'service failure never retries through another identity');
assert.match(publicActionLabel('approved'), /pelaksanaan belum dikonfirmasi/);
const linkContext = { exports: {}, URL };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./link.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, linkContext);
const link = linkContext.exports.publicLinkInfo;
assert.equal(link().url, 'http://localhost:8001/lapor'); assert.equal(link().local, true);
assert.equal(link('https://example.test/lapor').local, false);
for (const invalid of ['javascript:alert(1)', 'https://user:secret@example.test/lapor', 'https://example.test/lapor?token=private', 'https://example.test/operator']) assert.equal(link(invalid).local, true);
assert.equal(link('https://localhost/lapor').local, true);
console.log('PASS: public session validation, isolated Bearer requests, terminal auth failures, honest approved status and safe local/HTTPS QR links');
