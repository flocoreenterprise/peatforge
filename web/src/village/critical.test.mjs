import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./critical.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const present = context.exports.criticalPresentation;
const base = { level: 'RENDAH', pfvi: 25, wt_cm: 65, days_to_critical: 0 };
assert.equal(present(base).pfviLevel, 'RENDAH');
assert.equal(present(base).wtCritical, true);
assert.match(present(base).urgency, /sekarang/);
assert.equal(present({ ...base, wt_cm: 59.9, days_to_critical: 3 }).criticalNow, false);
assert.match(present({ ...base, wt_cm: 59.9, days_to_critical: 3 }).urgency, /dalam 3 hari; belum kritis sekarang/);
assert.equal(present({ ...base, wt_cm: 60 }).wtCritical, true);
assert.equal(present({ ...base, wt_cm: 20, pfvi: 250 }).criticalNow, true);
assert.equal(present({ ...base, wt_cm: null, pfvi: null, days_to_critical: null }).criticalNow, false);
assert.equal(present({ ...base, wt_cm: null, critical_now: true, critical_reason: 'wt', pfvi_level: 'SEDANG' }).pfviLevel, 'SEDANG');
assert.equal(present({ ...base, wt_cm: null, critical_now: true, critical_reason: 'wt' }).wtCritical, true);
console.log('PASS: 10 current/forecast critical presentation assertions; no API mutation');
