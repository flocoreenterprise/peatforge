import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const context = { exports: {} };
vm.runInNewContext(ts.transpileModule(readFileSync(new URL('./scenario.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const { scenarioGainText, hydraulicAssumptionText } = context.exports;
const setup = { spacing_m: 400, nodes: 51, conductivity_m_day: 4, specific_yield: 0.2, effective_hydraulic_thickness_m: 24, horizon_days: 14, boundary_application: 'both_endpoints', target_effect: 'single_symmetric_strip', provenance: 'team_assumption_not_field_calibrated' };
assert.match(scenarioGainText({ wt_gain_cm: 14.263, model_setup: setup }), /14 hari.*14,3 cm/);
assert.doesNotMatch(scenarioGainText({ wt_gain_cm: 14.263, model_setup: setup }), /9 cm/);
assert.match(scenarioGainText({ wt_gain_cm: 0, model_setup: setup }), /0 cm/);
assert.match(scenarioGainText({ wt_gain_cm: null }), /belum tersedia/);
assert.match(hydraulicAssumptionText(setup), /400 m.*24 m.*asumsi benchmark tim, bukan kedalaman gambut/);
assert.match(hydraulicAssumptionText({ ...setup, spacing_m: 350, effective_hydraulic_thickness_m: 18 }), /350 m.*18 m/);
assert.match(hydraulicAssumptionText(), /Metadata.*belum tersedia/);
const component = readFileSync(new URL('./VillageDetail.tsx', import.meta.url), 'utf8');
const start = component.indexOf('export function benefitText');
const end = component.indexOf('function CurveChart', start);
const benefitContext = { exports: {}, number: n => new Intl.NumberFormat('id-ID', { maximumFractionDigits: 1 }).format(n) };
vm.runInNewContext(ts.transpileModule(component.slice(start, end), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, benefitContext);
assert.match(benefitContext.exports.benefitText({ days_bought: 1, reason: null }), /1 hari tambahan/);
assert.match(benefitContext.exports.benefitText({ days_bought: null, reason: 'scenario_beyond_horizon', at_least_days: 2 }), /setidaknya 2 hari/);
assert.match(benefitContext.exports.benefitText({ days_bought: 0, reason: 'baseline_already_critical' }), /Kondisi awal sudah/);
console.log('PASS: 10 scenario/assumption assertions; no API mutation');
